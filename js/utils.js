const Utils = {
  // ===== Security =====
  escapeHTML(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  },

  // ===== Performance =====
  debounce(fn, wait = 250) {
    let timer = null;
    return function (...args) {
      clearTimeout(timer);
      timer = setTimeout(() => fn.apply(this, args), wait);
    };
  },

  // ===== Dates =====
  today() { return new Date().toISOString().slice(0, 10); },

  daysAgo(n) {
    const d = new Date();
    d.setDate(d.getDate() - n);
    return d.toISOString().slice(0, 10);
  },

  startOfWeek() {
    const d = new Date();
    d.setDate(d.getDate() - d.getDay());
    return d.toISOString().slice(0, 10);
  },

  startOfMonth() {
    const d = new Date();
    d.setDate(1);
    return d.toISOString().slice(0, 10);
  },

  currentMonth() { return new Date().toISOString().slice(0, 7); },

  // ===== Numbers =====
  clamp(n, min, max) { return Math.min(max, Math.max(min, n)); },

  round(n, digits = 0) {
    const p = Math.pow(10, digits);
    return Math.round(n * p) / p;
  },

  // ===== Validation =====
  isEgyptPhone(v) { return /^01[0-2,5]\d{8}$/.test(String(v || '').trim()); },

  // ===== Share helpers =====
  copyText(text) {
    return new Promise((resolve) => {
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(() => resolve(true)).catch(() => resolve(Utils.legacyCopy(text)));
      } else {
        resolve(Utils.legacyCopy(text));
      }
    });
  },

  legacyCopy(text) {
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      const ok = document.execCommand('copy');
      ta.remove();
      return ok;
    } catch (e) { return false; }
  },

  // ===== Meta =====
  appVersion() { return '2.0.0'; }
};
window.Utils = Utils;

// اختصار عالمي للتحصين
window.esc = Utils.escapeHTML;

